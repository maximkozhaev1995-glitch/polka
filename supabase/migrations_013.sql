-- Чек-лист смены: переделка на повторяющиеся шаблоны (ежедневные/по дню
-- недели) с журналом отметок (кто и когда выполнил).
alter table tasks add column if not exists recur text not null default 'daily';
alter table tasks add column if not exists weekday int;
alter table tasks add column if not exists active boolean not null default true;

-- Раньше любой сотрудник мог менять задачу через update (чтобы отмечать
-- done) — теперь отметки идут через task_log, а update остаётся только
-- для редактирования шаблона управляющим.
drop policy if exists tasks_update on tasks;
create policy tasks_update on tasks for update using (venue_id = me_venue() and me_role()='manager');

create table if not exists task_log (
  id bigint generated by default as identity primary key,
  venue_id uuid not null,
  task_id bigint not null references tasks(id) on delete cascade,
  on_date date not null,
  by_tg bigint,
  by_name text,
  at timestamptz not null default now(),
  unique(task_id, on_date)
);
alter table task_log enable row level security;
drop policy if exists task_log_read on task_log;
create policy task_log_read on task_log for select using (venue_id = me_venue());
drop policy if exists task_log_write on task_log;
create policy task_log_write on task_log for insert with check (venue_id = me_venue());
drop policy if exists task_log_delete on task_log;
create policy task_log_delete on task_log for delete using (venue_id = me_venue());
