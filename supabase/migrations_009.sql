-- Журнал инвентаризаций: запись итогов каждой завершённой инвентаризации
-- по категории (обычные/хука сигар/парфюм) — недостача в шт/г/₽.
create table if not exists inv_log (
  id bigint generated by default as identity primary key,
  venue_id uuid not null,
  ig text not null,
  items int not null default 0,
  shortage_units int not null default 0,
  shortage_g numeric not null default 0,
  price_per_g numeric,
  shortage_rub numeric,
  by_tg bigint,
  at timestamptz not null default now()
);
alter table inv_log enable row level security;
drop policy if exists inv_log_read on inv_log;
create policy inv_log_read on inv_log for select using (venue_id = me_venue());
drop policy if exists inv_log_write on inv_log;
create policy inv_log_write on inv_log for insert with check (venue_id = me_venue());
