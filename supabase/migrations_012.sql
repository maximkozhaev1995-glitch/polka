-- Чек-лист смены (общий список, управляющий добавляет, любой мастер отмечает)
-- и база знаний (файлы — регламенты, инструкции; управляющий загружает, все читают).
create table if not exists tasks (
  id bigint generated by default as identity primary key,
  venue_id uuid not null,
  text text not null,
  done boolean not null default false,
  done_by text,
  by_tg bigint,
  created_at timestamptz not null default now()
);
alter table tasks enable row level security;
drop policy if exists tasks_read on tasks;
create policy tasks_read on tasks for select using (venue_id = me_venue());
drop policy if exists tasks_insert on tasks;
create policy tasks_insert on tasks for insert with check (venue_id = me_venue() and me_role()='manager');
drop policy if exists tasks_update on tasks;
create policy tasks_update on tasks for update using (venue_id = me_venue());
drop policy if exists tasks_delete on tasks;
create policy tasks_delete on tasks for delete using (venue_id = me_venue() and me_role()='manager');

create table if not exists knowledge (
  id bigint generated by default as identity primary key,
  venue_id uuid not null,
  name text not null,
  path text not null,
  by_tg bigint,
  created_at timestamptz not null default now()
);
alter table knowledge enable row level security;
drop policy if exists knowledge_read on knowledge;
create policy knowledge_read on knowledge for select using (venue_id = me_venue());
drop policy if exists knowledge_write on knowledge;
create policy knowledge_write on knowledge for insert with check (venue_id = me_venue() and me_role()='manager');
drop policy if exists knowledge_delete on knowledge;
create policy knowledge_delete on knowledge for delete using (venue_id = me_venue() and me_role()='manager');

-- Файлы базы знаний лежат в том же бакете files/<venue_id>/knowledge/<файл> —
-- политика files_manager (миграция 011) уже разрешает управляющему писать туда.
-- Добавляем отдельную политику на чтение ТОЛЬКО папки knowledge для любого
-- сотрудника заведения (регламенты должна видеть вся команда). Файлы
-- контрагентов (папка contractors) остаются видны только управляющему.
drop policy if exists files_read_team on storage.objects;
create policy files_read_team on storage.objects for select
  using (bucket_id='files' and (storage.foldername(name))[1] = me_venue()::text and (storage.foldername(name))[2] = 'knowledge');
