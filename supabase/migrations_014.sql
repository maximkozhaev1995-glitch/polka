-- База знаний: категории (руководства) и разделы внутри них
-- (заголовок + текст + необязательный файл), вместо плоского списка файлов.
create table if not exists knowledge_cat (
  id bigint generated by default as identity primary key,
  venue_id uuid not null,
  name text not null,
  by_tg bigint,
  created_at timestamptz not null default now()
);
alter table knowledge_cat add column if not exists by_tg bigint;
alter table knowledge_cat enable row level security;
drop policy if exists knowledge_cat_read on knowledge_cat;
create policy knowledge_cat_read on knowledge_cat for select using (venue_id = me_venue());
drop policy if exists knowledge_cat_write on knowledge_cat;
create policy knowledge_cat_write on knowledge_cat for insert with check (venue_id = me_venue() and me_role()='manager');
drop policy if exists knowledge_cat_delete on knowledge_cat;
create policy knowledge_cat_delete on knowledge_cat for delete using (venue_id = me_venue() and me_role()='manager');

alter table knowledge add column if not exists cat_id bigint references knowledge_cat(id) on delete cascade;
alter table knowledge add column if not exists title text;
alter table knowledge add column if not exists body text;
alter table knowledge alter column path drop not null;
alter table knowledge alter column name drop not null;
