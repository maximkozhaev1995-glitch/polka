def classify(x):
    t=(x['n']+' '+x['d']+' '+x['l']).lower()
    c=[k for k,r in CATS if re.search(r,t)]
    if ('сигарный лист' in x['t'] or 'безаромка' in x['t']) and 'tobacco' not in c and not c: c.append('tobacco')
    if 'безаромка' in x['t'] and 'tobacco' not in c: c.append('tobacco')
    return c
if __name__=='__main__':
    G=json.load(open('data.json'))
    import collections
    cnt=collections.Counter();none=[]
    for x in G:
        c=classify(x);cnt.update(c)
        if not c: none.append((x['b'],x['n'],x['d']))
